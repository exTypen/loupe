#!/usr/bin/env python3
"""Regenerates Sources/Loupe/FileIconData.swift from Material Icon Theme (MIT, github.com/material-extensions/vscode-material-icon-theme)."""
import urllib.request, pathlib
VERSION = "5.39.0"
NAMES = """rust nix typescript react_ts javascript react json markdown yaml toml database go python swift html css sass console lock
image svg git readme license makefile settings file cucumber proto graphql vue svelte kotlin java c cpp h solidity terraform xml
table pdf zip tune docker nodejs tsconfig npm pnpm yarn bun vite eslint prettier ruby php lua elixir haskell zig dart csharp
kubernetes helm certificate key log font video audio jupyter test-ts test-js test-jsx editorconfig babel tailwindcss webpack nginx""".split()
out = ["// Generated by scripts/gen-file-icons.py — Material Icon Theme %s (MIT). Do not edit." % VERSION, "", "enum FileIconData {", "    static let svg: [String: String] = ["]
for n in NAMES:
    svg = urllib.request.urlopen(f"https://cdn.jsdelivr.net/npm/material-icon-theme@{VERSION}/icons/{n}.svg").read().decode()
    assert '"##' not in svg; out.append(f'        "{n}": ##"{svg.strip()}"##,')
out += ["    ]", "}", ""]
pathlib.Path(__file__).resolve().parent.parent.joinpath("Sources/Loupe/FileIconData.swift").write_text("\n".join(out))
print(f"wrote {len(NAMES)} icons")
