#!/usr/bin/env python3
"""Embeds the grammars' tags.scm queries (definitions and references) as Swift strings.

Run after `swift package resolve`, from the repo root:  scripts/gen-tag-queries.py
Embedding avoids shipping SwiftPM resource bundles inside the .app. The queries are MIT-licensed, like the grammars.
"""
import os

CO = ".build/checkouts"
# language id → tags.scm files, concatenated in order (TypeScript's extends JavaScript's).
QUERIES = {
    "rust": ["tree-sitter-rust/queries/tags.scm"],
    "swift": ["tree-sitter-swift/queries/tags.scm"],
    "go": ["tree-sitter-go/queries/tags.scm"],
    "javascript": ["tree-sitter-javascript/queries/tags.scm"],
    "typescript": ["tree-sitter-javascript/queries/tags.scm", "tree-sitter-typescript/queries/tags.scm"],
    "python": ["tree-sitter-python/queries/tags.scm"],
    "c": ["tree-sitter-c/queries/tags.scm"],
    "cpp": ["tree-sitter-c/queries/tags.scm", "tree-sitter-cpp/queries/tags.scm"],
    "java": ["tree-sitter-java/queries/tags.scm"],
}

out = ["// Generated by scripts/gen-tag-queries.py from the grammar packages' queries/tags.scm. Do not edit.", "",
       "enum TagQueries {", "    static let source: [String: String] = ["]
for lang, files in QUERIES.items():
    text = "\n".join(open(os.path.join(CO, f), encoding="utf-8").read() for f in files)
    out.append(f'        "{lang}": #"""')
    out.extend("        " + l if l else "" for l in text.rstrip("\n").split("\n"))
    out.append('        """#,')
out += ["    ]", "}", ""]
open("Sources/Loupe/TagQueries.swift", "w", encoding="utf-8").write("\n".join(out))
print("wrote Sources/Loupe/TagQueries.swift")
