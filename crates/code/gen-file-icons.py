#!/usr/bin/env python3
"""Regenerates crates/code/icons/*.svg and src/icon_data.rs from Material Icon Theme (MIT,
github.com/material-extensions/vscode-material-icon-theme). The Rust side embeds each SVG with include_str!.

    crates/code/gen-file-icons.py            # download the SVGs, then write src/icon_data.rs
    crates/code/gen-file-icons.py --offline  # only rewrite src/icon_data.rs from icons/
"""
import pathlib, sys, urllib.request

VERSION = "5.39.0"
NAMES = """rust nix typescript react_ts javascript react json markdown yaml toml database go python swift html css sass console lock
image svg git readme license makefile settings file cucumber proto graphql vue svelte kotlin java c cpp h solidity terraform xml
table pdf zip tune docker nodejs tsconfig npm pnpm yarn bun vite eslint prettier ruby php lua elixir haskell zig dart csharp
kubernetes helm certificate key log font video audio jupyter test-ts test-js test-jsx editorconfig babel tailwindcss webpack nginx""".split()

root = pathlib.Path(__file__).resolve().parent
icons = root / "icons"
if "--offline" not in sys.argv:
    icons.mkdir(exist_ok=True)
    for n in NAMES:
        svg = urllib.request.urlopen(f"https://cdn.jsdelivr.net/npm/material-icon-theme@{VERSION}/icons/{n}.svg").read().decode()
        (icons / f"{n}.svg").write_text(svg.strip())
out = [f"// Generated by crates/code/gen-file-icons.py: Material Icon Theme {VERSION} (MIT). Do not edit.", "",
       "pub static SVG: &[(&str, &str)] = &["]
out += [f'    ("{n}", include_str!("../icons/{n}.svg")),' for n in sorted(NAMES)]
out += ["];", ""]
(root / "src/icon_data.rs").write_text("\n".join(out))
print(f"wrote {len(NAMES)} icons")
